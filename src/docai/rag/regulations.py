def build_regulations() -> list[CorpusDoc]:
    docs: list[CorpusDoc] = []
    for doc_id, title, header, sections in _REGULATIONS:
        preamble = header[1] if len(header) > 1 else None
        doc = CorpusDoc(
            doc_id=doc_id,
            doc_kind="regulation",
            header=[title, header[0]],
            preamble=preamble,
            sections=[
                Section(
                    name,
                    [Clause(text, (fact,) if fact else ()) for text, fact in clauses],
                    numbered=name is not None,
                )
                for name, clauses in sections
            ],
            meta={"title": title.capitalize()},
        )
        doc.render()
        docs.append(doc)
    return docs
