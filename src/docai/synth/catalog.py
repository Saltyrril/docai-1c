def _round_price(value: float) -> Decimal:
    """Красивая цена: чем дороже, тем крупнее шаг округления."""
    if value < 100:
        return Decimal(f"{value:.2f}")
    if value < 1000:
        return Decimal(round(value))
    step = 10 if value < 10000 else 100
    return Decimal(round(value / step) * step)


def _build_category(rng: random.Random, category: str, quota: int) -> list[CatalogItem]:
    bases = _BASES[category]
    modifiers = ("", *_MODIFIERS[category])
    combos = [(base, mod) for base in bases for mod in modifiers]
    rng.shuffle(combos)
    chosen = combos[:quota]
    # Каждое базовое название хотя бы раз встречается без уточнения.
    present = {base.name for base, _ in chosen}
    for base in bases:
        if base.name not in present:
            chosen[rng.randrange(len(chosen))] = (base, "")
    items: list[CatalogItem] = []
    for base, mod in chosen:
        name = f"{base.name}, {mod}" if mod else base.name
        # Цена логарифмически равномерна в диапазоне базовой позиции.
        low, high = float(base.price_min), float(base.price_max)
        price = _round_price(low * (high / low) ** rng.random())
        items.append(
            CatalogItem(
                category=category,
                name=name,
                unit_name=base.unit.name,
                unit_code=base.unit.okei,
                integer_qty=base.unit.integer,
                qty_max=base.qty_max,
                price=price,
            )
        )
    return items


@cache
def get_catalog() -> tuple[CatalogItem, ...]:
    """Каталог из 500 позиций (строится один раз на процесс)."""
    rng = random.Random(CATALOG_SEED)
    items: list[CatalogItem] = []
    for category, quota in CATEGORY_QUOTA.items():
        items += _build_category(rng, category, quota)
    return tuple(items)


@cache
def items_by_category() -> dict[str, tuple[CatalogItem, ...]]:
    result: dict[str, list[CatalogItem]] = {c: [] for c in CATEGORY_QUOTA}
    for item in get_catalog():
        result[item.category].append(item)
    return {c: tuple(v) for c, v in result.items()}
